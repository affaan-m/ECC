#!/usr/bin/env node
/**
 * Bundles the block-no-verify package into one CommonJS file that ships with
 * the hooks. Plugin clones and installer copies have no node_modules, so the
 * hook loads this bundle instead of the package.
 *
 * Usage:
 *   node scripts/build-block-no-verify.js          write the bundle
 *   node scripts/build-block-no-verify.js --check  exit 1 if the bundle is stale
 */

'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const repoRoot = path.join(__dirname, '..');
const outfile = path.join(repoRoot, 'scripts', 'hooks', 'vendor', 'block-no-verify.cjs');
const entry = require.resolve('block-no-verify');
// The package's exports map hides package.json; entry is <pkg>/dist/cjs/index.js.
const { version } = JSON.parse(fs.readFileSync(path.join(entry, '..', '..', '..', 'package.json'), 'utf8'));

function build() {
  const result = esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    target: 'node18',
    format: 'cjs',
    legalComments: 'inline',
    banner: { js: `// Generated by scripts/build-block-no-verify.js from block-no-verify@${version}. Do not edit.` },
    write: false
  });
  return result.outputFiles[0].text;
}

const bundle = build();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outfile) ? fs.readFileSync(outfile, 'utf8') : '';
  if (current !== bundle) {
    console.error(`${path.relative(repoRoot, outfile)} is stale. Run: npm run build:block-no-verify`);
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  fs.writeFileSync(outfile, bundle);
}
